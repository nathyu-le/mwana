CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('analyst','admin') NOT NULL DEFAULT 'analyst'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE scans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, filename VARCHAR(220) NOT NULL,
 sha256 CHAR(64) CHARACTER SET ascii NOT NULL, status VARCHAR(24) NOT NULL,
 report MEDIUMTEXT NOT NULL, vt_report TEXT, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX personal_history(user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE vt_cache (
 sha256 CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 body TEXT NOT NULL, expires_at BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB;

CREATE TABLE settings (
 id TINYINT PRIMARY KEY,
 vt_next BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
